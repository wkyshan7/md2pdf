export function resolveTokens(preset: ThemePreset): ThemeTokens {
  return { ...DEFAULT_TOKENS, ...preset.tokens };
}

/** 合并用户自定义覆盖（例如从 localStorage 恢复） */
export function withOverrides(
  base: ThemeTokens,
  overrides: Partial<ThemeTokens> | undefined,
): ThemeTokens {
  return { ...base, ...(overrides ?? {}) };
}
